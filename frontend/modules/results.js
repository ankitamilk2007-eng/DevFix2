/**
 * DevFix AI — Results Presentation Module
 * 
 * Renders:
 * 1. Structured Diagnosis with separation of Traceback Facts vs AI Hypotheses
 * 2. Proposed Fix Diff Viewer with clear before/after highlighting
 * 3. Transparent Verification Report with real/demonstrated pass/fail counts
 */

import { escapeHtml } from './utils.js';

/**
 * Renders the structured diagnosis view
 */
export function renderDiagnosis(container, session, callbacks) {
  if (!session || !session.diagnosis) {
    container.innerHTML = `
      <div class="empty-state">
        <p class="empty-state-title">No diagnosis available</p>
        <p class="empty-state-desc">Submit a code snippet and traceback to generate an evidence-backed diagnosis.</p>
        <button class="btn btn-primary btn-sm" id="diagEmptyBackBtn">Go to Debug Form</button>
      </div>
    `;
    const backBtn = container.querySelector('#diagEmptyBackBtn');
    if (backBtn && callbacks.onReturnToInput) {
      backBtn.addEventListener('click', callbacks.onReturnToInput);
    }
    return;
  }

  const diag = session.diagnosis;
  const isDemo = diag.isDemonstration || session.isDemo;

  const factsHtml = (diag.tracebackFacts || [])
    .map(fact => `
      <li class="fact-item">
        <span class="fact-bullet">✓</span>
        <span>${escapeHtml(fact)}</span>
      </li>
    `).join('');

  container.innerHTML = `
    <!-- Top Diagnosis Summary Card -->
    <div class="diagnosis-header-card">
      <div class="diag-title-area">
        <div style="display: flex; align-items: center; gap: 0.75rem; flex-wrap: wrap;">
          <span class="diag-error-pill">
            <span>⚠️</span> ${escapeHtml(diag.errorType)}
          </span>
          <span class="diag-location-badge">
            📄 ${escapeHtml(diag.fileName || 'source.py')}${diag.culpritLine ? ` : Line ${diag.culpritLine}` : ''}
          </span>
        </div>
        <h2 class="diag-error-summary">${escapeHtml(diag.summary)}</h2>
      </div>
      <div>
        ${isDemo ? `
          <span class="diag-mode-tag" title="Generated by client demo engine while Flask backend is offline">
            ℹ️ Demo Analysis Mode
          </span>
        ` : `
          <span class="status-pill pill-verified">
            ● Live Backend Analysis
          </span>
        `}
      </div>
    </div>

    <!-- Two-Column Layout: Traceback Facts vs Diagnosis Hypotheses -->
    <div class="evidence-hypothesis-grid">
      <!-- Left Column: Facts extracted from Traceback -->
      <div class="section-box">
        <div class="section-box-header">
          <span class="badge-fact">Confirmed Facts</span>
          <h3 class="section-box-title">Traceback Evidence</h3>
        </div>
        <ul class="fact-list">
          ${factsHtml}
        </ul>
        ${diag.culpritCode ? `
          <div style="margin-top: 1rem;">
            <div style="font-size: 0.75rem; color: var(--text-muted); margin-bottom: 0.25rem;">
              Culprit line identified in call stack:
            </div>
            <div class="code-snippet-card">
              <code>${escapeHtml(diag.culpritCode)}</code>
            </div>
          </div>
        ` : ''}
      </div>

      <!-- Right Column: AI Hypothesis -->
      <div class="section-box">
        <div class="section-box-header">
          <span class="badge-hypothesis">AI Hypothesis</span>
          <h3 class="section-box-title">Likely Root Cause</h3>
        </div>
        <p class="hypothesis-body">
          ${escapeHtml(diag.hypothesis)}
        </p>
        <div style="margin-top: 1.25rem; padding-top: 0.75rem; border-top: 1px solid var(--border-subtle);">
          <div style="font-size: 0.75rem; color: var(--text-muted); margin-bottom: 0.25rem;">
            Recommended Next Step:
          </div>
          <div style="font-size: 0.8125rem; color: var(--accent-primary); font-weight: 500;">
            ${escapeHtml(diag.recommendedAction)}
          </div>
        </div>
      </div>
    </div>

    <!-- Plain-Language Explanation Card -->
    <div class="explanation-card">
      <h3 class="explanation-title">Beginner-Friendly Explanation</h3>
      <p class="explanation-text">
        ${escapeHtml(diag.explanation)}
      </p>
    </div>

    <!-- Actions Bar -->
    <div class="diagnosis-actions">
      <button class="btn btn-secondary" id="diagReturnToEditBtn">
        ← Edit Submitted Code
      </button>
      <div style="display: flex; gap: 0.75rem;">
        <button class="btn btn-primary btn-lg" id="diagProceedToFixBtn">
          Review Proposed Fix →
        </button>
      </div>
    </div>
  `;

  // Attach event listeners
  const returnBtn = container.querySelector('#diagReturnToEditBtn');
  if (returnBtn && callbacks.onReturnToInput) {
    returnBtn.addEventListener('click', callbacks.onReturnToInput);
  }

  const proceedBtn = container.querySelector('#diagProceedToFixBtn');
  if (proceedBtn && callbacks.onProceedToFix) {
    proceedBtn.addEventListener('click', callbacks.onProceedToFix);
  }
}

/**
 * Renders the proposed fix view with diff comparison
 */
export function renderProposedFix(container, session, callbacks) {
  if (!session || !session.proposedFix) {
    container.innerHTML = `
      <div class="empty-state">
        <p class="empty-state-title">No proposed fix available</p>
        <p class="empty-state-desc">Diagnose an error first to receive a minimal patch proposal.</p>
        <button class="btn btn-primary btn-sm" id="fixEmptyBackBtn">Back to Diagnosis</button>
      </div>
    `;
    const backBtn = container.querySelector('#fixEmptyBackBtn');
    if (backBtn && callbacks.onReturnToDiagnosis) {
      backBtn.addEventListener('click', callbacks.onReturnToDiagnosis);
    }
    return;
  }

  const fix = session.proposedFix;
  const isDemo = fix.isDemonstration || session.isDemo;

  // Build diff lines comparison
  const diffHtml = generateDiffHtml(
    fix.originalSnippet || session.code,
    fix.fixedSnippet || fix.fullFixedCode
  );

  const isUnmodified = fix.isUnmodified || fix.canSynthesize === false || fix.noFixGenerated === true;
  const fixTitle = isUnmodified ? 'Manual Correction Required' : 'Proposed Minimal Code Patch';

  container.innerHTML = `
    <!-- Fix Summary Card -->
    <div class="fix-summary-card">
      <div style="display: flex; justify-content: space-between; align-items: flex-start; gap: 1rem; flex-wrap: wrap;">
        <div>
          <h2 class="fix-summary-title">${fixTitle}</h2>
          <p class="fix-summary-desc">${escapeHtml(fix.summary)}</p>
          <span class="fix-affected-lines">Affected: ${escapeHtml(fix.affectedLines || 'Source block')}</span>
        </div>
        ${isUnmodified ? `
          <span class="status-pill pill-unverified">⚠️ Manual Input Required</span>
        ` : (isDemo ? `
          <span class="diag-mode-tag">ℹ️ Demo Proposal</span>
        ` : `
          <span class="status-pill pill-verified">● Live AI Model Proposal</span>
        `)}
      </div>
      <div style="margin-top: 0.75rem; font-size: 0.8125rem; color: var(--text-secondary);">
        <strong>${isUnmodified ? 'Status & Action:' : 'Why this resolves the error:'}</strong> ${escapeHtml(fix.explanation)}
      </div>
    </div>

    ${isUnmodified ? `
      <div class="alert-banner alert-warning" style="margin-bottom: 1rem;">
        <span class="alert-icon">⚠️</span>
        <div class="alert-content">
          <strong>No Automated Fix Generated:</strong> The system was unable to automatically synthesize a correction for this error. The code below remains unpatched. <em>Warning: Running verification on unchanged code will result in failure.</em> Please edit the code directly in the editor below to apply your intended fix before submitting for verification.
        </div>
      </div>
    ` : ''}

    <!-- Diff Viewer -->
    <div class="diff-viewer-card">
      <div class="diff-header">
        <span>${isUnmodified ? 'Current Code (Unmodified)' : 'Code Modification Preview'}</span>
        <div class="diff-legend">
          ${isUnmodified 
            ? '<span class="legend-del">● No automated changes applied</span>' 
            : '<span class="legend-del">− Original Code</span><span class="legend-add">+ Proposed Change</span>'
          }
        </div>
      </div>
      <div class="diff-body">
        ${diffHtml}
      </div>
    </div>

    <!-- Editable Code Review Area -->
    <div class="fix-editor-card">
      <div class="fix-editor-header">
        <span>Approved Code for Verification</span>
        <span class="fix-editor-hint">${isUnmodified ? 'Edit code directly here to apply your fix before running tests' : 'Inspect or adjust the exact code that the verification sandbox will execute'}</span>
      </div>
      <textarea id="fixCodeEditor" class="fix-code-textarea" rows="9" spellcheck="false">${escapeHtml(fix.fullFixedCode || session.code)}</textarea>
    </div>

    <!-- Approval & Verification Disclaimer Notice -->
    <div class="approval-notice-card">
      <strong>⚠️ Controlled Verification Notice:</strong>
      Approving this proposal confirms you accept the code above for <em>subprocess test execution</em>. It does <strong>not</strong> mean the fix is already verified. Real verification results will be evaluated and displayed after executing in the isolated sandbox.
    </div>

    <!-- Actions Bar -->
    <div class="fix-actions-bar">
      <button class="btn btn-secondary" id="fixBackToDiagBtn">
        ← Back to Diagnosis
      </button>
      <div class="fix-actions-right">
        <button class="btn btn-outline-danger" id="fixRejectBtn">
          ✕ Reject Fix
        </button>
        <button class="btn btn-primary btn-lg" id="fixApproveBtn">
          Approve Fix & Run Verification →
        </button>
      </div>
    </div>
  `;

  // Attach event listeners
  const backBtn = container.querySelector('#fixBackToDiagBtn');
  if (backBtn && callbacks.onReturnToDiagnosis) {
    backBtn.addEventListener('click', callbacks.onReturnToDiagnosis);
  }

  const rejectBtn = container.querySelector('#fixRejectBtn');
  if (rejectBtn && callbacks.onRejectFix) {
    rejectBtn.addEventListener('click', callbacks.onRejectFix);
  }

  const approveBtn = container.querySelector('#fixApproveBtn');
  if (approveBtn && callbacks.onApproveFix) {
    approveBtn.addEventListener('click', () => {
      const editor = container.querySelector('#fixCodeEditor');
      const approvedCode = editor ? editor.value : (fix.fullFixedCode || session.code);
      callbacks.onApproveFix(approvedCode);
    });
  }
}

/**
 * Generates unified diff HTML with clean line markings
 */
function generateDiffHtml(originalText, fixedText) {
  const origLines = (originalText || '').split('\n');
  const fixLines = (fixedText || '').split('\n');

  let rows = '';
  let origIdx = 1;
  let fixIdx = 1;

  // Simple clean diff viewer for single snippet replacement
  origLines.forEach(line => {
    rows += `
      <div class="diff-row diff-deleted">
        <div class="diff-gutter">${origIdx++}</div>
        <div class="diff-marker">−</div>
        <div class="diff-code-text">${escapeHtml(line)}</div>
      </div>
    `;
  });

  fixLines.forEach(line => {
    rows += `
      <div class="diff-row diff-added">
        <div class="diff-gutter">${fixIdx++}</div>
        <div class="diff-marker">+</div>
        <div class="diff-code-text">${escapeHtml(line)}</div>
      </div>
    `;
  });

  return rows;
}

/**
 * Renders the dedicated verification report
 */
export function renderVerification(container, session, callbacks) {
  if (!session || !session.verification) {
    container.innerHTML = `
      <div class="empty-state">
        <p class="empty-state-title">No verification data</p>
        <p class="empty-state-desc">Approve a proposed fix to trigger controlled test verification.</p>
        <button class="btn btn-primary btn-sm" id="vEmptyBackBtn">Back to Proposed Fix</button>
      </div>
    `;
    const backBtn = container.querySelector('#vEmptyBackBtn');
    if (backBtn && callbacks.onReturnToFix) {
      backBtn.addEventListener('click', callbacks.onReturnToFix);
    }
    return;
  }

  const v = session.verification;
  const isVerified = v.status === 'verified';
  const isFailed = v.status === 'failed';
  const isUnverified = v.status === 'unverified';

  let bannerClass = 'banner-unverified';
  let bannerIcon = '⏳';
  let bannerTitle = 'Fix Unverified';
  let bannerSub = 'Controlled tests could not be executed or were unavailable.';

  if (isVerified) {
    bannerClass = 'banner-verified';
    bannerIcon = '✓';
    bannerTitle = 'Fix Verified';
    bannerSub = 'All defined test checks executed and passed in the controlled runner.';
  } else if (isFailed) {
    bannerClass = 'banner-failed';
    bannerIcon = '✕';
    bannerTitle = 'Verification Failed';
    bannerSub = 'One or more required tests failed or threw errors.';
  }

  const testCasesHtml = (v.testCases && v.testCases.length > 0)
    ? v.testCases.map(tc => `
      <li class="test-item">
        <div class="test-item-left">
          <span class="${tc.status === 'passed' ? 'test-badge-pass' : 'test-badge-fail'}">
            ${tc.status === 'passed' ? 'PASSED' : 'FAILED'}
          </span>
          <span class="test-name">${escapeHtml(tc.name)}</span>
        </div>
        <div class="test-item-right">
          <span>Input: ${escapeHtml(tc.input || 'None')}</span>
        </div>
      </li>
    `).join('')
    : `
      <li class="test-item">
        <div class="test-item-left">
          <span class="status-pill pill-unverified">NO TESTS RUN</span>
          <span class="test-name">${escapeHtml(v.scope || 'No test suite was linked.')}</span>
        </div>
      </li>
    `;

  container.innerHTML = `
    <!-- Verification Status Banner -->
    <div class="verification-status-banner ${bannerClass}">
      <div class="vstatus-left">
        <div class="vstatus-icon-circle">${bannerIcon}</div>
        <div>
          <h2 class="vstatus-title">${bannerTitle}</h2>
          <p class="vstatus-subtitle">${bannerSub}</p>
        </div>
      </div>
      <div class="vstatus-counts">
        <div class="vcount-item">
          <div class="vcount-num" style="color: var(--text-primary);">${v.testsExecuted || 0}</div>
          <div class="vcount-label">Executed</div>
        </div>
        <div class="vcount-item">
          <div class="vcount-num" style="color: var(--color-success);">${v.testsPassed || 0}</div>
          <div class="vcount-label">Passed</div>
        </div>
        <div class="vcount-item">
          <div class="vcount-num" style="color: var(--color-danger);">${v.testsFailed || 0}</div>
          <div class="vcount-label">Failed</div>
        </div>
      </div>
    </div>

    ${v.disclaimer ? `
      <div class="alert-banner alert-warning">
        <span class="alert-icon">⚠️</span>
        <div class="alert-content">
          ${escapeHtml(v.disclaimer)}
        </div>
      </div>
    ` : ''}

    <!-- Test Suite Details -->
    <div class="test-suite-card">
      <div class="panel-header">
        <div class="panel-title-group">
          <h3 class="panel-title">Executed Verification Tests</h3>
          <span class="panel-subtitle">${escapeHtml(v.scope || 'Controlled execution checks')}</span>
        </div>
      </div>
      <ul class="test-list">
        ${testCasesHtml}
      </ul>
    </div>

    <!-- Execution Console Output -->
    <div class="console-card">
      <div class="console-header">
        <span>Terminal Execution Log (stdout / stderr)</span>
        <span>Environment: ${v.isDemonstration ? 'Local Demo Runner' : 'Isolated Flask Sandbox'}</span>
      </div>
      <div class="console-body">${escapeHtml(v.stdout || 'No standard output recorded.')}${v.stderr ? `\n\n<span class="console-stderr">${escapeHtml(v.stderr)}</span>` : ''}</div>
    </div>

    <!-- Verification Scope & Limitations -->
    <div class="verification-scope-card">
      <div class="scope-title">Evidence & Scope Transparency</div>
      <p>
        DevFix AI maintains an evidence-backed verification boundary. A fix is marked <strong>Verified</strong> ONLY when unit tests directly exercise the modified code and pass with return code 0. If execution environments are offline or unavailable, fixes remain marked <strong>Unverified</strong> to safeguard against unproven AI generations.
      </p>
    </div>

    <!-- Actions Bar -->
    <div class="diagnosis-actions">
      <button class="btn btn-secondary" id="vBackToFixBtn">
        ← Back to Proposed Fix
      </button>
      <div style="display: flex; gap: 0.75rem;">
        <button class="btn btn-secondary" id="vViewInHistoryBtn">
          View in History 📋
        </button>
        <button class="btn btn-primary" id="vStartNewSessionBtn">
          + Start New Debug Session
        </button>
      </div>
    </div>
  `;

  // Attach event listeners
  const backBtn = container.querySelector('#vBackToFixBtn');
  if (backBtn && callbacks.onReturnToFix) {
    backBtn.addEventListener('click', callbacks.onReturnToFix);
  }

  const historyBtn = container.querySelector('#vViewInHistoryBtn');
  if (historyBtn && callbacks.onViewHistory) {
    historyBtn.addEventListener('click', callbacks.onViewHistory);
  }

  const newSessionBtn = container.querySelector('#vStartNewSessionBtn');
  if (newSessionBtn && callbacks.onStartNewSession) {
    newSessionBtn.addEventListener('click', callbacks.onStartNewSession);
  }
}
